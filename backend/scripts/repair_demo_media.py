"""Restore missing encrypted media for the seeded demo samples.

The seed's images are deterministic (synth.generate(kind, label, seed)), so each missing image can be
regenerated byte-for-byte. A regenerated image is only stored if its SHA-256 equals the hash already
recorded (and signed) for that sample, so signatures, manifests and dataset Merkle roots stay valid.
Real captures are never touched.

    cd backend && python scripts/repair_demo_media.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app import crypto, storage, synth  # noqa: E402
from app.db import Dataset, SessionLocal, Sample, init_db  # noqa: E402

# (kind, labels in seed order, samples per label, seed0) per seeded device, mirroring seed.py
SEEDED = {
    "vd-asha-field-01": [("leaf", ["healthy", "pest_damage", "fungal_spot"], 40, 1)],
    "vd-garage-bay-02": [("damage", ["dent", "scratch", "cracked_glass"], 32, 50_000)],
    "vd-fleet-dash-07": [("road", ["rain_night", "clear_night"], 36, 90_000)],
    "vd-retail-aisle-04": [("shelf", ["shelf_stocked", "shelf_empty"], 36, 130_000),
                           ("ir", ["empty", "occupied_1", "occupied_many"], 30, 170_000)],
}
INSURANCE_SEEDS = [777_000, 777_001, 777_002, 778_001, 778_002, 778_003, 778_004]


def missing(s: Sample) -> bool:
    try:
        storage.get_ciphertext(s.storage_ref)
        return False
    except FileNotFoundError:
        return True


def candidates(s: Sample):
    for kind, labels, n_per, seed0 in SEEDED.get(s.device_id or "", []):
        if s.label in labels:
            i = labels.index(s.label)
            for j in range(n_per):
                yield kind, seed0 + i * 1000 + j
    for seed in INSURANCE_SEEDS:  # insurance tamper-demo photos
        yield "damage", seed


def main() -> None:
    init_db()
    db = SessionLocal()
    rows = [s for s in db.query(Sample).filter(Sample.is_demo == True).all() if missing(s)]  # noqa: E712
    print(f"demo samples with missing media: {len(rows)}")
    fixed, failed = 0, []
    for s in rows:
        img = next((b for kind, seed in candidates(s)
                    for b in [synth.generate(kind, s.label, seed)] if crypto.sha256_hex(b) == s.media_sha256), None)
        if img is None:
            failed.append(s.id)
            continue
        s.storage_ref, s.key_wrapped = storage.put_encrypted(img, s.id)
        if not s.preview_file or not (storage.PREVIEWS / s.preview_file).exists():
            s.preview_file = storage.make_preview(img, s.id, blur=False)
        fixed += 1
        if fixed % 100 == 0:
            db.commit()
            print(f"  restored {fixed}…")
    db.commit()
    print(f"restored {fixed} (hash-verified against the signed record); could not match {len(failed)}")
    if failed:
        print("  unmatched:", ", ".join(x[:8] for x in failed[:10]))
    db.close()


if __name__ == "__main__":
    main()
